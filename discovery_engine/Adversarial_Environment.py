import jax
import jax.numpy as jnp
from typing import Callable, Tuple

# ==============================================================================
# PROJECT BUDDHA: ADVERSARIAL HAMILTONIAN ENVIRONMENT (CREATOR VS SOLVER)
# ==============================================================================

class AdversarialUniverse:
    """
    Takes an Energy Function H(q, p) generated by the Creator AI,
    uses JAX Autodiff to derive the laws of motion, and generates the dataset.
    """
    def __init__(self, creator_hamiltonian: Callable):
        self.H = creator_hamiltonian
        
        # JAX Autodiff: The magic happens here.
        # dot_q =  dH/dp
        # dot_p = -dH/dq
        self.grad_H = jax.grad(self.H, argnums=(0, 1)) # Differentiate w.r.t q (0) and p (1)

    @jax.jit(static_argnums=0)
    def equations_of_motion(self, q: jnp.ndarray, p: jnp.ndarray) -> Tuple[jnp.ndarray, jnp.ndarray]:
        """
        Automatically derives the physical laws of this universe.
        """
        dH_dq, dH_dp = self.grad_H(q, p)
        dot_q = dH_dp
        dot_p = -dH_dq
        return dot_q, dot_p

    def calculate_creator_reward(self, q_trajectory: jnp.ndarray, p_trajectory: jnp.ndarray, solver_mse: float) -> float:
        """
        Rewards the Creator AI.
        Win Condition 1: High Chaos (Non-linear movement, high variance).
        Win Condition 2: Solver failed to reverse-engineer the Hamiltonian (High solver_mse).
        Penalty: Energy explosion (NaNs).
        """
        if jnp.isnan(q_trajectory).any() or jnp.isnan(p_trajectory).any():
            return -1.0 # Penalize broken physics
            
        # Proxy for chaos: Standard deviation of the momentum changes
        chaos_metric = jnp.std(jnp.diff(p_trajectory, axis=0))
        
        # Reward = Chaos + Solver's Failure
        reward = chaos_metric + solver_mse
        return float(reward)

