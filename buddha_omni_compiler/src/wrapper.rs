use crate::ast::OdeSystem;
use crate::emitter::{emit_derivatives_function, emit_params_struct};
use crate::pratyaksh::PRATYAKSH_CPP_SOURCE;

#[derive(Debug, Clone)]
pub struct SimConfig {
    pub integrator: String, // "pratyaksh_b", "pratyaksh_a", "rk4"
    pub t_start: f64,
    pub t_end: f64,
    pub dt: f64,
    pub beta: f64,
    pub record_trajectory: bool,
    pub traj_stride: usize,
}

impl Default for SimConfig {
    fn default() -> Self {
        Self {
            integrator: "pratyaksh_b".to_string(),
            t_start: 0.0,
            t_end: 10.0,
            dt: 0.01,
            beta: 0.50,
            record_trajectory: false,
            traj_stride: 100,
        }
    }
}

pub fn generate_cpp_source(system: &OdeSystem, _config: &SimConfig) -> String {
    let mut code = String::new();

    code.push_str(r#"/**
 * Auto-generated by Project Buddha Omni-Compiler
 * Target: FFI Shared Library (Batch IC + Early Abort)
 */
#include <vector>
#include <cmath>
#include <chrono>
#include <limits>

"#);

    code.push_str(&emit_params_struct(system));
    code.push_str("\n");
    code.push_str(&emit_derivatives_function(system));
    code.push_str("\n");
    code.push_str(PRATYAKSH_CPP_SOURCE);
    code.push_str("\n");

    code.push_str(r#"
extern "C" {
    struct SimulationResultC {
        int status; // 0=SUCCESS, 1=DIVERGED, 2=ABORTED_UNPHYSICAL
        double final_time;
        size_t steps_taken;
        size_t throttled_steps;
        double max_denominator;
        double execution_time_sec;
    };

    void run_simulation_batch(
        size_t num_ics,
        const double* y0_batch, 
        size_t dim, 
        double t_start, double t_end, double dt, double beta, 
        int integrator_choice, // 0=pratyaksh_ii, 1=rk4
        double* final_y_batch, 
        SimulationResultC* results
    ) {
        SystemParams params;
        
        for (size_t b = 0; b < num_ics; ++b) {
            std::vector<double> y(dim);
            for(size_t d=0; d<dim; ++d) {
                y[d] = y0_batch[b * dim + d];
            }

            std::vector<double> k1(dim, 0.0);
            std::vector<double> k2(dim, 0.0);
            std::vector<double> k3(dim, 0.0);
            std::vector<double> k4(dim, 0.0);
            std::vector<double> temp(dim, 0.0);

            double t = t_start;
            size_t steps_taken = 0;
            size_t throttled_steps = 0;
            double max_denominator = 1.0;
            int status = 0; // SUCCESS

            auto start_time = std::chrono::high_resolution_clock::now();

            while (t < t_end - 1e-12) {
                double current_dt = dt;
                if (t + current_dt > t_end) current_dt = t_end - t;

                pratyaksh::StepResult res;
                if (integrator_choice == 0) {
                    res = pratyaksh::step_pratyaksh_ii(t, current_dt, y, k1, k2, k3, k4, temp, compute_derivatives, params, 1.0, beta);
                } else {
                    res = pratyaksh::step_rk4(t, current_dt, y, k1, k2, k3, k4, temp, compute_derivatives, params);
                }

                if (res.denominator > max_denominator) max_denominator = res.denominator;
                if (res.is_throttled) throttled_steps++;

                // Early-Stopping Guillotine
                if (res.denominator > 1e10) {
                    status = 2; // ABORTED_UNPHYSICAL
                    break;
                }

                bool diverged = false;
                for (size_t d = 0; d < dim; ++d) {
                    if (std::isnan(y[d]) || std::isinf(y[d])) {
                        diverged = true;
                        break;
                    }
                }
                
                if (diverged) {
                    status = 1; // DIVERGED
                    break;
                }

                t += current_dt;
                steps_taken++;
            }

            auto end_time = std::chrono::high_resolution_clock::now();
            double exec_time = std::chrono::duration<double>(end_time - start_time).count();

            // Save results
            results[b].status = status;
            results[b].final_time = t;
            results[b].steps_taken = steps_taken;
            results[b].throttled_steps = throttled_steps;
            results[b].max_denominator = max_denominator;
            results[b].execution_time_sec = exec_time;

            for(size_t d=0; d<dim; ++d) {
                final_y_batch[b * dim + d] = y[d];
            }
        }
    }
}
"#);

    code
}
